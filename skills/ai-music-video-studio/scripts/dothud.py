class Grid:
    def __init__(s,cols,rows): s.c,s.r=cols,rows; s.px={}
    def text(s,x,y,t,col=1):
        for ch in t:
            rows=F[ch].split(); w=len(rows[0])
            for j,row in enumerate(rows):
                for i,b in enumerate(row):
                    if b=='1': s.px[(x+i,y+j)]=col
            x+=w+1
        return x
    def rect(s,x,y,w,h,col=1,fill=True):
        for i in range(w):
            for j in range(h):
                if fill or i in(0,w-1) or j in(0,h-1): s.px[(x+i,y+j)]=col
    def render(s,pitch=14,rad=5,bg=(0,0,0,0),off=None,cols=None,glow=0):
        W,H=s.c*pitch,s.r*pitch; im=Image.new('RGBA',(W,H),bg); d=ImageDraw.Draw(im)
        for i in range(s.c):
            for j in range(s.r):
                cx,cy=i*pitch+pitch/2,j*pitch+pitch/2
                k=s.px.get((i,j))
                fill=cols[k] if k else off
                if fill: d.ellipse((cx-rad,cy-rad,cx+rad,cy+rad),fill=fill)
        if glow:
            g=im.filter(ImageFilter.GaussianBlur(glow)); im=Image.alpha_composite(g,im)
        return im
def warning_grid(title,l1,l2,level=8,total=10):
    g=Grid(72,48)
    g.text(3,3,'▲',2); g.text(13,3,title,2)
    g.text(3,15,l1,1); g.text(3,26,l2,1)
    for n in range(total):
        x=3+n*6
        if n<level: g.rect(x,38,5,5,2 if n>=total-3 else 1)
        else: g.rect(x,38,5,5,1,fill=False)
    return g
